// sampleType 构造一个覆盖常见规则的合成 IR。
func sampleType() ir.TypeRules {
	return ir.TypeRules{
		Name: "User",
		Fields: []ir.FieldRules{
			{
				GoName: "Name", JSONName: "name", Kind: ir.KindString,
				Rules: []ir.Rule{{Name: "required"}, {Name: "min", Raw: "3", Literal: "3"}},
			},
			{
				GoName: "Email", JSONName: "email", Kind: ir.KindString, IsPointer: true,
				Rules: []ir.Rule{{Name: "omitempty"}, {Name: "email"}},
			},
			{
				GoName: "Age", JSONName: "age", Kind: ir.KindSigned, BitSize: 64,
				Rules: []ir.Rule{{Name: "omitempty"}, {Name: "gte", Raw: "0", Literal: "0"}, {Name: "lte", Raw: "150", Literal: "150"}},
			},
			{
				GoName: "Role", JSONName: "role", Kind: ir.KindString,
				Rules: []ir.Rule{{Name: "oneof", Raw: "admin user", Args: []string{"admin", "user"}}},
			},
			{
				GoName: "Note", JSONName: "note", Kind: ir.KindString,
				Rules: []ir.Rule{{Name: "max", Raw: "50", Literal: "50"}},
			},
		},
	}
}

func TestGenerateBasic(t *testing.T) {
	src, err := Generate(Options{PackageName: "dto", Types: []ir.TypeRules{sampleType()}})
	if err != nil {
		t.Fatalf("Generate() err = %v", err)
	}
	out := string(src)
	for _, want := range []string{
		"// Code generated by valgen; DO NOT EDIT.",
		"package dto",
		"func (x *User) Validate() error",
		"var errs []error",
		"return errors.Join(errs...)",
		`&valerr.FieldError{Field: "name", Code: "required"}`,
		"check.Runes(string(x.Name)) < 3",
		"if x.Email == nil",
		"!check.Email(string(*x.Email))",
		"check.Runes(string(x.Note)) > 50",
		"int64(x.Age) < 0",
		"!check.OneOfString(string(x.Role), \"admin\", \"user\")",
		`"github.com/formal-you/validation-gen/pkg/check"`,
		`"github.com/formal-you/validation-gen/pkg/valerr"`,
	} {
		if !strings.Contains(out, want) {
			t.Errorf("生成结果缺少 %q", want)
		}
	}
}

func TestGenerateDeterministic(t *testing.T) {
	opts := Options{PackageName: "dto", Types: []ir.TypeRules{sampleType()}}
	a, err := Generate(opts)
	if err != nil {
		t.Fatal(err)
	}
	b, err := Generate(opts)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(a, b) {
		t.Fatal("Generate 结果不稳定（多次生成有 diff）")
	}
}

func TestGenerateNoRules(t *testing.T) {
	src, err := Generate(Options{
		PackageName: "dto",
		Types: []ir.TypeRules{{
			Name:   "Empty",
			Fields: []ir.FieldRules{{GoName: "A", JSONName: "a", Kind: ir.KindString}},
		}},
	})
	if err != nil {
		t.Fatalf("Generate() err = %v", err)
	}
	out := string(src)
	if !strings.Contains(out, "func (x *Empty) Validate() error") {
		t.Fatal("缺少 Validate 方法")
	}
	if strings.Contains(out, "errors.Join") {
		t.Fatal("无规则类型不应使用 errors.Join")
	}
	if strings.Contains(out, "github.com/formal-you/validation-gen/pkg/check") {
		t.Fatal("无规则类型不应导入 check")
	}
	if strings.Contains(out, "github.com/formal-you/validation-gen/pkg/valerr") {
		t.Fatal("无规则类型不应导入 valerr")
	}
}

func TestGenerateFillDefaults(t *testing.T) {
	src, err := Generate(Options{
		PackageName: "dto",
		Types: []ir.TypeRules{{
			Name: "Settings",
			Fields: []ir.FieldRules{
				{
					GoName: "Role", JSONName: "role", Kind: ir.KindString,
					Rules:   []ir.Rule{{Name: "required"}},
					Default: &ir.Default{Literal: `"guest"`, Raw: "guest"},
				},
				{
					GoName: "Page", JSONName: "page", Kind: ir.KindSigned, BitSize: 64,
					Default: &ir.Default{Literal: "1", Raw: "1"},
				},
			},
		}},
	})
	if err != nil {
		t.Fatalf("Generate() err = %v", err)
	}
	out := string(src)
	for _, want := range []string{
		"func (x *Settings) FillDefaults()",
		`if x.Role == "" {`,
		`x.Role = "guest"`,
		"if x.Page == 0 {",
		"x.Page = 1",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("生成结果缺少 %q", want)
		}
	}
}

func TestWriteFileAtomic(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "zz_generated.validation.go")

	if err := WriteFile(path, []byte("package dto\n")); err != nil {
		t.Fatalf("WriteFile() err = %v", err)
	}
	got, err := os.ReadFile(path)
	if err != nil || string(got) != "package dto\n" {
		t.Fatalf("读取文件失败或内容不符: %v %q", err, got)
	}

	// 不应残留临时文件。
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	if len(entries) != 1 {
		t.Fatalf("目录应只有目标文件，实际 %d 个: %v", len(entries), entries)
	}
}

// TestGoldenExampleDTO 是 golden 测试：用 gengo 解析 example/dto，
// 重新生成并与提交的 zz_generated.validation.go 逐字节比较。
func TestGoldenExampleDTO(t *testing.T) {
	p := gengoparser.New()
	if err := p.LoadPackages("github.com/formal-you/validation-gen/example/dto"); err != nil {
		t.Fatalf("gengo 加载失败: %v", err)
	}
	u, err := p.NewUniverse()
	if err != nil {
		t.Fatalf("NewUniverse() err = %v", err)
	}
	requested := p.UserRequestedPackages()
	if len(requested) != 1 {
		t.Fatalf("期望 1 个 package，实际 %v", requested)
	}
	pkg := u[requested[0]]

	names := []string{"CreateUserRequest", "UserProfile", "Order", "Settings", "NoValidate", "WebRequest"}
	var trs []ir.TypeRules
	for _, name := range names {
		tr, err := parser.ParseType(pkg.Path, pkg.Types[name])
		if err != nil {
			t.Fatalf("ParseType(%s) err = %v", name, err)
		}
		trs = append(trs, tr)
	}
	got, err := Generate(Options{PackageName: pkg.Name, Types: trs})
	if err != nil {
		t.Fatalf("Generate() err = %v", err)
	}

	committed, err := os.ReadFile(filepath.Join("..", "..", "example", "dto", "zz_generated.validation.go"))
	if err != nil {
		t.Fatalf("读取提交的生成文件失败: %v", err)
	}
	if !bytes.Equal(got, committed) {
		t.Fatal("重新生成结果与提交的 zz_generated.validation.go 不一致，请运行 go generate ./example/dto 后重新提交")
	}
}
