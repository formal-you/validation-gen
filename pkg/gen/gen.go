// Package gen 把规则 IR（pkg/ir）渲染为静态校验 Go 代码。
//
// 生成的代码：
//   - 无反射，只依赖标准库 errors 与公共包 err/check；
//   - 字段与规则顺序稳定，多次生成无 diff；
//   - 语义与 go-playground/validator/v10 一致：同一字段只报告
//     tag 顺序中第一个失败的规则（required/omitempty/pointer 短路语义见 README）。
package gen

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/formal-you/validation-gen/pkg/ir"
)

// errImport / checkImport 是生成代码依赖的公共包路径。
const (
	errImport   = "github.com/formal-you/validation-gen/pkg/errorx"
	checkImport = "github.com/formal-you/validation-gen/pkg/check"
)

// Options 是生成器的输入。
type Options struct {
	// PackageName 是目标 package 名（生成文件与 DTO 同包）。
	PackageName string
	// Types 是要生成校验方法的类型列表。
	Types []ir.TypeRules
}

// Generate 生成并返回 gofmt 后的 Go 源码。
func Generate(opts Options) ([]byte, error) {
	if opts.PackageName == "" {
		return nil, fmt.Errorf("PackageName 不能为空")
	}
	useerr, useCheck := importsUsed(opts.Types)

	var b strings.Builder
	b.WriteString("// Code generated by valgen; DO NOT EDIT.\n")
	b.WriteString("// 源：github.com/formal-you/validation-gen/cmd/valgen\n")
	b.WriteString("// 规则语义与 go-playground/validator/v10（v10.30.1）一致。\n\n")
	fmt.Fprintf(&b, "package %s\n\n", opts.PackageName)

	if useerr || useCheck {
		b.WriteString("import (\n")
		if useerr {
			b.WriteString("\t\"errors\"\n\n")
			fmt.Fprintf(&b, "\t%q\n", errImport)
		}
		if useCheck {
			fmt.Fprintf(&b, "\t%q\n", checkImport)
		}
		b.WriteString(")\n\n")
	}

	for _, tr := range opts.Types {
		genValidate(&b, tr)
		genFillDefaults(&b, tr)
	}

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("生成代码 gofmt 失败（生成器缺陷）: %w\n%s", err, b.String())
	}
	return src, nil
}

// importsUsed 判断生成文件实际需要哪些 import：
// errors/err 在存在可执行规则（非纯 omitempty）时引入，check 在存在
// 长度/数值/oneof/email 规则时引入，避免生成未使用的 import。
func importsUsed(types []ir.TypeRules) (useerr, useCheck bool) {
	for _, tr := range types {
		for _, f := range tr.Fields {
			for _, r := range enforceableRules(f) {
				useerr = true
				if r.Name != "required" {
					useCheck = true
				}
			}
		}
	}
	return useerr, useCheck
}

// enforceableRules 返回字段中真正需要执行检查的规则（去掉纯修饰符 omitempty）。
func enforceableRules(f ir.FieldRules) []ir.Rule {
	var out []ir.Rule
	for _, r := range f.Rules {
		if r.Name == "omitempty" {
			continue
		}
		out = append(out, r)
	}
	return out
}

// genValidate 生成 Validate() 方法体。
func genValidate(b *strings.Builder, tr ir.TypeRules) {
	fields := make([]ir.FieldRules, 0, len(tr.Fields))
	for _, f := range tr.Fields {
		if len(enforceableRules(f)) > 0 {
			fields = append(fields, f)
		}
	}

	fmt.Fprintf(b, "// Validate 校验 %s 的静态规则（v1 白名单）。\n", tr.Name)
	b.WriteString("// 与 validator/v10 语义一致：同一字段只报告 tag 顺序中第一个失败的规则；\n")
	b.WriteString("// 不修改接收对象，不调用 FillDefaults。\n")
	fmt.Fprintf(b, "func (x *%s) Validate() error {\n", tr.Name)
	if len(fields) == 0 {
		b.WriteString("\treturn nil\n")
		fmt.Fprintf(b, "}\n\n")
		return
	}
	b.WriteString("\tvar errs []error\n")
	for _, f := range fields {
		genFieldChecks(b, f)
	}
	b.WriteString("\treturn errors.Join(errs...)\n")
	fmt.Fprintf(b, "}\n\n")
}

// genFieldChecks 渲染单个字段的 else-if 失败链。
func genFieldChecks(b *strings.Builder, f ir.FieldRules) {
	expr := "x." + f.GoName
	var conds []cond
	if f.IsPointer {
		// 指针字段：nil 时按 validator 语义短路：
		// 首条规则为 omitempty -> 跳过剩余规则；否则报告第一条规则的 code。
		firstCode := ""
		if len(f.Rules) > 0 && f.Rules[0].Name != "omitempty" {
			firstCode = f.Rules[0].Name
		}
		conds = append(conds, cond{expr: expr + " == nil", code: firstCode})
		for _, r := range f.Rules[1:] {
			if r.Name == "required" || r.Name == "omitempty" {
				// 非 nil 时 required/omitempty 恒通过（与 validator 一致），跳过。
				continue
			}
			conds = append(conds, cond{expr: failExpr(r, "*"+expr, f.Kind), code: r.Name})
		}
	} else {
		for _, r := range f.Rules {
			if r.Name == "omitempty" {
				conds = append(conds, cond{expr: expr + " == " + zeroLiteral(f.Kind), skip: true})
				continue
			}
			conds = append(conds, cond{expr: failExpr(r, expr, f.Kind), code: r.Name})
		}
	}

	fieldLit := strconv.Quote(f.JSONName)
	var lines []string
	for i, c := range conds {
		if i == 0 {
			lines = append(lines, "\tif "+c.expr+" {")
		} else {
			lines = append(lines, "\t} else if "+c.expr+" {")
		}
		if c.skip || c.code == "" {
			lines = append(lines, "\t\t// omitempty: 跳过剩余规则")
		} else {
			lines = append(lines, "\t\terrs = append(errs, &errorx.FieldError{Field: "+fieldLit+", Code: "+strconv.Quote(c.code)+"})")
		}
	}
	lines = append(lines, "}")
	b.WriteString(strings.Join(lines, "\n") + "\n")
}

// cond 表示失败链中的一个条件。
type cond struct {
	expr string
	code string
	skip bool
}

// failExpr 返回规则失败（需要报错）的 Go 布尔表达式。
func failExpr(r ir.Rule, v string, kind ir.Kind) string {
	switch kind {
	case ir.KindString:
		// helper 调用统一显式转 string，兼容 named string 类型。
		switch r.Name {
		case "required":
			return v + ` == ""`
		case "min", "gte":
			return "check.Runes(string(" + v + ")) < " + r.Literal
		case "max", "lte":
			return "check.Runes(string(" + v + ")) > " + r.Literal
		case "gt":
			return "check.Runes(string(" + v + ")) <= " + r.Literal
		case "lt":
			return "check.Runes(string(" + v + ")) >= " + r.Literal
		case "len":
			return "check.Runes(string(" + v + ")) != " + r.Literal
		case "oneof":
			return "!check.OneOfString(string(" + v + "), " + quotedArgs(r.Args) + ")"
		case "email":
			return "!check.Email(string(" + v + "))"
		}
	case ir.KindBool:
		if r.Name == "required" {
			return v + " == false"
		}
	case ir.KindSigned:
		switch r.Name {
		case "required":
			return v + " == 0"
		case "min", "gte":
			return "int64(" + v + ") < " + r.Literal
		case "max", "lte":
			return "int64(" + v + ") > " + r.Literal
		case "gt":
			return "int64(" + v + ") <= " + r.Literal
		case "lt":
			return "int64(" + v + ") >= " + r.Literal
		case "len":
			return "int64(" + v + ") != " + r.Literal
		case "oneof":
			return "!check.OneOfInt(int64(" + v + "), " + quotedArgs(r.Args) + ")"
		}
	case ir.KindUnsigned:
		switch r.Name {
		case "required":
			return v + " == 0"
		case "min", "gte":
			return "uint64(" + v + ") < " + r.Literal
		case "max", "lte":
			return "uint64(" + v + ") > " + r.Literal
		case "gt":
			return "uint64(" + v + ") <= " + r.Literal
		case "lt":
			return "uint64(" + v + ") >= " + r.Literal
		case "len":
			return "uint64(" + v + ") != " + r.Literal
		case "oneof":
			return "!check.OneOfUint(uint64(" + v + "), " + quotedArgs(r.Args) + ")"
		}
	case ir.KindFloat:
		switch r.Name {
		case "required":
			return v + " == 0"
		case "min", "gte":
			return floatCmp(v, r.Literal, " < ")
		case "max", "lte":
			return floatCmp(v, r.Literal, " > ")
		case "gt":
			return floatCmp(v, r.Literal, " <= ")
		case "lt":
			return floatCmp(v, r.Literal, " >= ")
		case "len":
			return floatCmp(v, r.Literal, " != ")
		}
	}
	// 解析器已保证合法组合，这里兜底 panic 便于尽早暴露生成器缺陷。
	panic(fmt.Sprintf("gen: 未支持的规则 %q 与类型 %v 组合", r.Name, kind))
}

// floatCmp 生成浮点比较表达式。float32 字段统一转 float32 字面量比较，
// 与 validator 的 asFloat32 语义一致（参数先按 32 位解析再比较）。
func floatCmp(v, literal, op string) string {
	return v + op + literal
}

// quotedArgs 把 oneof 候选项转为 Go 字符串字面量列表。
func quotedArgs(args []string) string {
	quoted := make([]string, 0, len(args))
	for _, a := range args {
		quoted = append(quoted, strconv.Quote(a))
	}
	return strings.Join(quoted, ", ")
}

// zeroLiteral 返回各类型族的零值字面量。
func zeroLiteral(kind ir.Kind) string {
	switch kind {
	case ir.KindString:
		return `""`
	case ir.KindBool:
		return "false"
	default:
		return "0"
	}
}

// genFillDefaults 生成 FillDefaults() 方法。
func genFillDefaults(b *strings.Builder, tr ir.TypeRules) {
	var defaults []ir.FieldRules
	for _, f := range tr.Fields {
		if f.Default != nil {
			defaults = append(defaults, f)
		}
	}
	fmt.Fprintf(b, "// FillDefaults 为 %s 的零值字段填充 default 值，幂等，不覆盖非零值。\n", tr.Name)
	fmt.Fprintf(b, "func (x *%s) FillDefaults() {\n", tr.Name)
	for _, f := range defaults {
		fmt.Fprintf(b, "\tif x.%s == %s {\n\t\tx.%s = %s\n\t}\n",
			f.GoName, zeroLiteral(f.Kind), f.GoName, f.Default.Literal)
	}
	fmt.Fprintf(b, "}\n\n")
}

// WriteFile 原子写入生成文件：先写临时文件再 rename，
// 生成失败时不会覆盖已有生成文件。
func WriteFile(path string, data []byte) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, ".valgen-*.tmp")
	if err != nil {
		return fmt.Errorf("创建临时文件失败: %w", err)
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		return fmt.Errorf("写入临时文件失败: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("关闭临时文件失败: %w", err)
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return fmt.Errorf("设置文件权限失败: %w", err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return fmt.Errorf("替换生成文件失败: %w", err)
	}
	return nil
}
